package ch.ost.i.dsl.ssr;

import org.springframework.data.domain.Sort;
import org.springframework.stereotype.Controller;
import org.springframework.ui.Model;
import org.springframework.web.bind.WebDataBinder;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.InitBinder;
import org.springframework.web.bind.annotation.ModelAttribute;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.PostMapping;

@Controller
public class ProductController {
    
    private final ProductRepository productRepository;
        
    public ProductController(ProductRepository productRepository) {
        this.productRepository = productRepository;
    }
        
    // The id is generated by the database: a form field must not overwrite an existing product
    @InitBinder
    public void disallowId(WebDataBinder binder) {
        binder.setDisallowedFields("id");
    }

    @GetMapping({"/", "/products"})
    public String listProducts(Model model) {
        model.addAttribute("products", productRepository.findAll(Sort.by("id")));
        model.addAttribute("newProduct", new Product());
        return "products";
    }
    
    @PostMapping("/products")
    public String createProduct(@ModelAttribute Product product) {
        productRepository.save(product);
        return "redirect:/products";
    }
    
    @PostMapping("/products/{id}/buy")
    public String buy(@PathVariable Long id) {
        productRepository.buy(id);
        return "redirect:/products";
    }
}
